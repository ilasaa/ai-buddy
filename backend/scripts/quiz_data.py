def seed_quizzes(db):
    from sqlalchemy import select

    from app.models import KnowledgeQuiz

    for slug, title, questions in QUIZZES:
        if not db.scalar(select(KnowledgeQuiz).where(KnowledgeQuiz.slug == slug)):
            db.add(
                KnowledgeQuiz(
                    slug=slug,
                    title=title,
                    passing_score=2,
                    questions=[
                        dict(text=text, options=options, correct=correct, explanation=explanation)
                        for text, options, correct, explanation in questions
                    ],
                )
            )
    db.flush()
